-- ===================================================================
-- lua/custom/readonly_hint.lua
-- 「閲覧専用だからできない」ことを日本語で伝える
--
-- 単に無効にすると、押しても無反応か、E21 のような英語の内部エラーが
-- 出るだけで理由が伝わらない。この道具の前提（編集はエージェントに頼む）
-- を、詰まったその場で伝えるためのもの。
-- ===================================================================

local M = {}

---@param what? string 何をしようとしたか（例: "削除"）
function M.explain(what)
  local head = what and ("%s はできません"):format(what) or "この操作はできません"
  vim.notify(head .. "。このビューアーは閲覧専用です。\n" ..
    "左ペインのエージェントへ依頼してください。", vim.log.levels.INFO)
end

return M
